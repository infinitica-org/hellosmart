"""Heuristic authorship-iteration signals, from parsed git history + currently checked-out text.

Ported from ProjAgentScan's src/checks/provenance/ai_boilerplate_signals.py (logic unchanged;
the fact-store wrapper was dropped, consuming parsed Commits directly instead of a
`commit_history` fact -- see package docstring).

Whether a file's content arrived in one large commit with little follow-up ("low iteration"),
and whether its current text contains generic placeholder markers. The 500-line, 0.95 and
COSMETIC_CHANGE_LINES thresholds, and which phrases count as "boilerplate", are heuristic
choices (rigor H) -- a signal, never proof that a file was or wasn't genuinely iterated on.

  edit_concentration          fraction of a file's total added lines that arrived in its first
                               commit (1.0 = never touched again)
  revision_count               commits after the first that touched it
  substantive_revision_count   of those, how many changed more than COSMETIC_CHANGE_LINES lines
                               (added+removed) -- a commit that only tweaks whitespace doesn't
                               count as real iteration
  summary.files_with_low_iteration       revision_count == 0 and edit_concentration >= 0.95
  summary.files_with_stuffed_revisions   revision_count > 0 but substantive_revision_count == 0:
                               every follow-up commit was cosmetic, so the file *looks* iterated
                               on but isn't ("signal stuffing")
"""

from __future__ import annotations

import re
from typing import TypedDict

from .git_log import Commit

LARGE_COMMIT_LINES = 500
LOW_ITERATION_CONCENTRATION = 0.95
COSMETIC_CHANGE_LINES = 2
MAX_FILES_LISTED = 50
MAX_FLAGGED_LISTED = 50

_PATTERNS = [
    ("generated_by_marker", re.compile(r"#\s*generated by|//\s*generated by", re.IGNORECASE)),
    (
        "ai_disclaimer",
        re.compile(r"as an ai language model|i cannot (?:assist|help) with that", re.IGNORECASE),
    ),
    ("placeholder_todo", re.compile(r"TODO:?\s*implement(?:\s+this)?\b", re.IGNORECASE)),
    ("placeholder_stub", re.compile(r"\bpass\s*#\s*(?:stub|placeholder)\b", re.IGNORECASE)),
]


class FileRevisionRow(TypedDict):
    path: str
    edit_concentration: float
    revision_count: int
    substantive_revision_count: int


class BoilerplateFlagRow(TypedDict):
    file: str
    flags: list[str]


class BoilerplateSummary(TypedDict):
    files_with_low_iteration: int
    files_with_stuffed_revisions: int


class BoilerplateSignals(TypedDict):
    large_single_commit_pct: float
    files: list[FileRevisionRow]
    summary: BoilerplateSummary


def analyze_revision_history(commits: list[Commit]) -> BoilerplateSignals:
    per_file_changes: dict[str, list[tuple[int, int]]] = {}
    for commit in commits:
        for f in commit["files"]:
            per_file_changes.setdefault(f["path"], []).append((f["added"], f["removed"]))

    files_rows: list[FileRevisionRow] = []
    large_commit_count = 0
    low_iteration = 0
    stuffed = 0
    for path, changes in sorted(per_file_changes.items()):
        added_sequence = [added for added, _removed in changes]
        total_added = sum(added_sequence)
        first_added = added_sequence[0]
        concentration = round(first_added / total_added, 3) if total_added else 1.0
        revision_count = len(changes) - 1
        substantive_revision_count = sum(
            1 for added, removed in changes[1:] if added + removed > COSMETIC_CHANGE_LINES
        )
        if first_added > LARGE_COMMIT_LINES:
            large_commit_count += 1
        if revision_count == 0 and concentration >= LOW_ITERATION_CONCENTRATION:
            low_iteration += 1
        if revision_count > 0 and substantive_revision_count == 0:
            stuffed += 1
        files_rows.append(
            {
                "path": path, "edit_concentration": concentration,
                "revision_count": revision_count,
                "substantive_revision_count": substantive_revision_count,
            }
        )

    large_pct = (
        round(large_commit_count / len(per_file_changes) * 100, 2) if per_file_changes else 0.0
    )
    return {
        "large_single_commit_pct": large_pct,
        "files": files_rows[:MAX_FILES_LISTED],
        "summary": {
            "files_with_low_iteration": low_iteration,
            "files_with_stuffed_revisions": stuffed,
        },
    }


def find_boilerplate_markers(path_and_text: list[tuple[str, str]]) -> list[BoilerplateFlagRow]:
    flagged: list[BoilerplateFlagRow] = []
    for rel, text in path_and_text:
        found = [label for label, pattern in _PATTERNS if pattern.search(text)]
        if found:
            flagged.append({"file": rel, "flags": found})
    return flagged[:MAX_FLAGGED_LISTED]
